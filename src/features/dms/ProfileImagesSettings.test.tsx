import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
const mock = vi.hoisted(() => ({ status: vi.fn(), save: vi.fn(), sync: vi.fn(), test: vi.fn(), folders: vi.fn(), connect: vi.fn(), notify: vi.fn(), canEdit: true }))
vi.mock('@/lib/auth', () => ({ useAuthUser: () => ({ user: { email: 'admin@amnex.com' } }) }))
vi.mock('@/lib/rbacTree', () => ({ useNodeAccess: () => mock.canEdit }))
vi.mock('./profileImagesClient', () => ({ PROFILE_IMAGES_QUERY: ['profileImages'], notifyProfileImages: mock.notify,
  profileImagesApi: { status: { query: mock.status }, save: { mutate: mock.save }, sync: { mutate: mock.sync }, test: { mutate: mock.test }, folders: { query: mock.folders }, connect: { mutate: mock.connect } } }))
import { ProfileImagesSettings } from './ProfileImagesSettings'
const saved = { folderId: 'folder-a', folderName: 'Team', accountEmail: 'admin@amnex.com', status: 'connected', imageCount: 2, matchedCount: 1, lastSyncAt: '2026-10-20T06:00:00Z', error: null, warnings: [], oauthReady: true }
beforeEach(() => {
  vi.stubEnv('VITE_API_BASE_URL', 'http://localhost:8088'); vi.clearAllMocks(); mock.canEdit = true
  mock.status.mockResolvedValue(saved); mock.save.mockResolvedValue({ ...saved, folderId: 'folder-b' }); mock.sync.mockResolvedValue(saved)
  mock.test.mockResolvedValue({ id: 'folder-b', name: 'New team' }); mock.folders.mockResolvedValue({ files: [{ id: 'folder-b', name: 'New team' }] })
})
afterEach(() => vi.unstubAllEnvs())
async function setup() {
  render(<QueryClientProvider client={new QueryClient({ defaultOptions: { queries: { retry: false } } })}><ProfileImagesSettings /></QueryClientProvider>)
  await screen.findByRole('group', { name: 'Selected photo folder' })
}
describe('Profile Images settings', () => {
  it('shows the saved folder by name, accepts a pasted link and refreshes after saving', async () => {
    await setup(); expect(screen.getByText('People matched')).toBeInTheDocument()
    expect(within(screen.getByRole('group', { name: 'Selected photo folder' })).getByText('Team')).toBeInTheDocument()
    expect(screen.queryByRole('textbox')).not.toBeInTheDocument()
    expect(screen.queryByText(/folder-a|Folder ID:/)).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Paste folder link' }))
    const input = screen.getByLabelText('Google Drive folder link')
    expect(input).toHaveValue('')
    fireEvent.change(input, { target: { value: 'https://drive.google.com/drive/folders/folder-b' } })
    expect(screen.queryByText('Folder ID: folder-b')).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Test Connection' }))
    await screen.findByText('Connection successful: New team'); expect(mock.save).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: /^Save$/ }))
    await waitFor(() => expect(mock.notify).toHaveBeenCalledTimes(1))
    expect(mock.save).toHaveBeenCalledWith({ folder: 'https://drive.google.com/drive/folders/folder-b' })
  })
  it('browses accessible folders and syncs the saved folder with an immediate refresh notification', async () => {
    await setup(); fireEvent.click(screen.getByRole('button', { name: 'Sync Now' }))
    await waitFor(() => expect(mock.notify).toHaveBeenCalled())
    fireEvent.click(screen.getByRole('button', { name: 'Browse folders' }))
    fireEvent.click(await screen.findByRole('button', { name: 'Use folder New team' }))
    expect(mock.folders).toHaveBeenCalledWith({ parentId: 'root' })
    expect(within(screen.getByRole('group', { name: 'Selected photo folder' })).getByText('New team')).toBeInTheDocument()
    expect(screen.queryByText(/folder-b/)).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Sync Now' })).toBeDisabled()
    expect(screen.queryByRole('group', { name: 'Google Drive folder browser' })).not.toBeInTheDocument()
  })
  it('shows My Drive folder names without IDs and navigates one folder at a time', async () => {
    await setup()
    mock.folders.mockResolvedValueOnce({ files: [{ id: 'folder-b', name: 'New team' }], nextPageToken: 'root-next' })
      .mockResolvedValueOnce({ files: [{ id: 'photos-id', name: 'Profile photos' }] })
      .mockResolvedValueOnce({ files: [] })
      .mockResolvedValueOnce({ files: [{ id: 'folder-b', name: 'New team' }] })
    fireEvent.click(screen.getByRole('button', { name: 'Browse folders' }))
    await screen.findByRole('button', { name: 'Open New team' })
    expect(screen.queryByRole('combobox')).not.toBeInTheDocument()
    expect(screen.queryByText('New team (folder-b)')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Back to parent folder' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: 'Open New team' }))
    await screen.findByRole('button', { name: 'Open Profile photos' })
    expect(mock.folders).toHaveBeenLastCalledWith({ parentId: 'folder-b' })
    expect(screen.queryByRole('button', { name: 'Load more folders' })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Open Profile photos' }))
    await screen.findByText('No subfolders here. You can use this folder.')
    expect(mock.folders).toHaveBeenLastCalledWith({ parentId: 'photos-id' })
    fireEvent.click(screen.getByRole('button', { name: 'My Drive' }))
    await screen.findByRole('button', { name: 'Open New team' })
    expect(mock.folders).toHaveBeenLastCalledWith({ parentId: 'root' })
    expect(screen.getByRole('button', { name: 'Back to parent folder' })).toBeDisabled()
  })
  it('selects the current folder even when it has no subfolders', async () => {
    await setup()
    mock.folders.mockResolvedValueOnce({ files: [{ id: 'photos-id', name: 'Profile photos' }] }).mockResolvedValueOnce({ files: [] })
    fireEvent.click(screen.getByRole('button', { name: 'Browse folders' }))
    fireEvent.click(await screen.findByRole('button', { name: 'Open Profile photos' }))
    await screen.findByText('No subfolders here. You can use this folder.')
    fireEvent.click(screen.getByRole('button', { name: 'Use this folder' }))
    expect(within(screen.getByRole('group', { name: 'Selected photo folder' })).getByText('Profile photos')).toBeInTheDocument()
    expect(screen.queryByText(/photos-id/)).not.toBeInTheDocument()
    expect(screen.getByText('Selected Profile photos. Save to apply.')).toBeInTheDocument()
  })
  it('loads more folders only for the currently opened parent and supports going back', async () => {
    await setup()
    mock.folders.mockResolvedValueOnce({ files: [{ id: 'folder-b', name: 'New team' }] })
      .mockResolvedValueOnce({ files: [{ id: 'photos-id', name: 'Profile photos' }], nextPageToken: 'team-next' })
      .mockResolvedValueOnce({ files: [{ id: 'other-id', name: 'Other photos' }] })
      .mockResolvedValueOnce({ files: [{ id: 'folder-b', name: 'New team' }] })
    fireEvent.click(screen.getByRole('button', { name: 'Browse folders' }))
    fireEvent.click(await screen.findByRole('button', { name: 'Open New team' }))
    fireEvent.click(await screen.findByRole('button', { name: 'Load more folders' }))
    await screen.findByRole('button', { name: 'Open Other photos' })
    expect(mock.folders).toHaveBeenLastCalledWith({ parentId: 'folder-b', pageToken: 'team-next' })
    expect(screen.getByRole('button', { name: 'Open Profile photos' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Back to parent folder' }))
    await screen.findByRole('button', { name: 'Open New team' })
    expect(mock.folders).toHaveBeenLastCalledWith({ parentId: 'root' })
  })
  it('rejects malformed URLs and disables configuration actions without DMS edit permission', async () => {
    await setup(); fireEvent.click(screen.getByRole('button', { name: 'Paste folder link' }))
    fireEvent.change(screen.getByLabelText('Google Drive folder link'), { target: { value: 'https://evil.example/folder' } })
    expect(screen.getByRole('button', { name: /^Save$/ })).toBeDisabled()
    mock.canEdit = false
    fireEvent.change(screen.getByLabelText('Google Drive folder link'), { target: { value: 'folder-b' } })
    expect(screen.getByRole('button', { name: /^Save$/ })).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Test Connection' })).toBeDisabled()
  })
  it('shows persisted sync errors and ambiguous matching diagnostics', async () => {
    mock.status.mockResolvedValue({ ...saved, status: 'error', error: 'Google Drive access denied.', warnings: ['Ambiguous filename: Jane Doe.jpg'] })
    await setup(); expect(screen.getByRole('alert')).toHaveTextContent('Google Drive access denied.')
    expect(screen.getByText('1 photo needs attention')).toBeInTheDocument()
  })
  it('reports zero matches clearly instead of showing a generic sync success', async () => {
    mock.sync.mockResolvedValue({ ...saved, imageCount: 31, matchedCount: 0 })
    await setup(); fireEvent.click(screen.getByRole('button', { name: 'Sync Now' }))
    await screen.findByText('Team: 0 of 31 photos matched to people.')
  })
  it('removes a folder through an explicit action without requiring an empty ID field', async () => {
    mock.save.mockResolvedValue({ ...saved, folderId: '', folderName: '', imageCount: 0, matchedCount: 0 })
    await setup(); fireEvent.click(screen.getByRole('button', { name: 'Remove folder' }))
    expect(screen.getByText('No folder selected')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: /^Save$/ }))
    await waitFor(() => expect(mock.save).toHaveBeenCalledWith({ folder: '' }))
    await screen.findByText('Drive profile images are disabled.')
  })
})
