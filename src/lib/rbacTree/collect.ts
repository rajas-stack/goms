import type { RbacNodeDef } from '@goms/domain'
import { declaredNodes } from './registry'

/**
 * Collects the permission-tree manifest. Runs only under Vite / Vitest (`import.meta.glob`): it imports every source file
 * that declares nodes (calls `definePermissionNodes` / `defineSection` / `defineNode`) and the router, then returns what
 * the registry holds. Discovery is by construction — a new declaration anywhere under src/ is picked up automatically.
 */

const DECLARES = /\b(definePermissionNodes|defineSection|defineNode)\(/
const SELF = /^\/src\/lib\/rbacTree\/(registry|collect)\.ts$/

export const sourceFiles = (): Record<string, string> =>
  import.meta.glob('/src/**/*.{ts,tsx}', { query: '?raw', import: 'default', eager: true }) as Record<string, string>

export interface RouteInfo { path: string; nodeId: string | null; redirect: boolean }

interface RouteLike { path?: string; handle?: { rbac?: { id?: string } }; element?: { type?: unknown }; children?: RouteLike[] }

export async function collectManifest(): Promise<{ nodes: RbacNodeDef[]; routes: RouteInfo[]; files: string[] }> {
  const sources = sourceFiles()
  const loaders = import.meta.glob('/src/**/*.{ts,tsx}')
  const files = Object.keys(sources).sort().filter((p) => !p.includes('.test.') && !SELF.test(p) && DECLARES.test(sources[p]))
  for (const file of files) await loaders[file]()
  const { router } = await import('@/app/router')
  const { Navigate } = await import('react-router-dom')
  const routes: RouteInfo[] = []
  const walk = (list: RouteLike[] | undefined) => list?.forEach((r) => {
    if (r.path) routes.push({ path: r.path, nodeId: r.handle?.rbac?.id ?? null, redirect: r.element?.type === Navigate })
    walk(r.children)
  })
  walk(router.routes as RouteLike[])
  return { nodes: declaredNodes(), routes, files }
}

export function renderManifest(nodes: readonly RbacNodeDef[]): string {
  const body = nodes.map((n) => `  ${JSON.stringify(n)},`).join('\n')
  return `// Generated by \`npm run rbac:manifest\` (src/lib/rbacTree/collect.ts). Do not edit by hand.
import type { RbacNodeDef } from './types.js'

export const RBAC_NODE_MANIFEST: readonly RbacNodeDef[] = [
${body}
]
`
}
