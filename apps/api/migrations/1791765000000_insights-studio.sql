-- Insights Studio: saved visualization components and the reports (templates) composed from them. The spec / layout
-- JSON is validated by the router against the semantic data catalog (packages/domain/src/insightsStudio/validate.ts),
-- so a stored visual can only name data sources and fields that exist. Personal by default; `shared` makes a row
-- visible to everyone with Insights access (editable by its owner, or by Role & Access managers).
-- insert_seq breaks ties between rows written in the same millisecond (see 1791764900000_insert-order-tiebreaker.sql).
CREATE TABLE insight_visuals (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name         TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 120),
  description  TEXT NOT NULL DEFAULT '' CHECK (char_length(description) <= 1000),
  spec         JSONB NOT NULL CHECK (jsonb_typeof(spec) = 'object' AND pg_column_size(spec) <= 65536),
  owner_email  TEXT NOT NULL,
  shared       BOOLEAN NOT NULL DEFAULT false,
  created_at   TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  insert_seq   BIGINT GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX insight_visuals_owner_idx ON insight_visuals (lower(owner_email));
CREATE INDEX insight_visuals_shared_idx ON insight_visuals (shared) WHERE shared;

CREATE TABLE insight_reports (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name         TEXT NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 120),
  description  TEXT NOT NULL DEFAULT '' CHECK (char_length(description) <= 1000),
  layout       JSONB NOT NULL CHECK (jsonb_typeof(layout) = 'array' AND pg_column_size(layout) <= 262144),
  filters      JSONB NOT NULL DEFAULT '{"period":{"kind":"all"}}' CHECK (jsonb_typeof(filters) = 'object'),
  owner_email  TEXT NOT NULL,
  shared       BOOLEAN NOT NULL DEFAULT false,
  created_at   TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  insert_seq   BIGINT GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX insight_reports_owner_idx ON insight_reports (lower(owner_email));
CREATE INDEX insight_reports_shared_idx ON insight_reports (shared) WHERE shared;

